package domain

/**
 * Модель агента - специализированного AI ассистента с предопределенной ролью и промптом.
 *
 * Агенты используются для создания контекстно-зависимых диалогов, где AI принимает
 * определенную роль (например, менеджер ресторана, шеф-повар) и ведет беседу
 * в соответствии с этой ролью.
 *
 * @property id Уникальный идентификатор агента (используется для сохранения выбранного агента)
 * @property name Отображаемое имя агента (показывается в UI)
 * @property description Краткое описание функций агента (показывается в селекторе)
 * @property icon Emoji иконка агента для визуальной идентификации
 * @property systemPrompt Системный промпт, который определяет поведение и роль агента.
 *                        Этот промпт отправляется в начале каждого диалога и задает контекст
 *                        для всех последующих ответов AI.
 *
 * @sample
 * ```kotlin
 * val customAgent = Agent(
 *     id = "translator",
 *     name = "Переводчик",
 *     description = "Перевод текстов на разные языки",
 *     icon = "🌐",
 *     systemPrompt = "Ты - профессиональный переводчик. Переводи тексты точно и естественно."
 * )
 * ```
 */
data class Agent(
    val id: String,
    val name: String,
    val description: String,
    val icon: String,
    val systemPrompt: String
) {
    /**
     * Компаньон объект с предопределенными агентами и утилитарными методами.
     */
    companion object {
        /**
         * Агент менеджера ресторана.
         *
         * Специализируется на организации корпоративных мероприятий и новогодних праздников.
         * Ведет интерактивный диалог, собирая информацию о количестве гостей, бюджете,
         * предпочтениях по меню и напиткам, после чего составляет детальный план мероприятия.
         */
        val RESTAURANT_MANAGER = Agent(
            id = "restaurant_manager",
            name = "Менеджер ресторана",
            description = "Организация корпоративов и мероприятий",
            icon = "🎉",
            systemPrompt = """Ты - опытный менеджер ресторана, специализирующийся на организации корпоративных мероприятий.
                |Твоя задача - задать клиенту от 4 до 10 уточняющих вопросов для организации новогоднего корпоратива.
                |
                |Собери следующую информацию:
                |1. Количество гостей
                |2. Бюджет мероприятия
                |3. Дата и продолжительность
                |4. Предпочтения по меню
                |5. Предпочтения по напиткам
                |6. Особые пожелания (развлечения, декор, музыка и т.д.)
                |
                |После сбора всей информации предоставь детальный план мероприятия с рекомендациями и примерной стоимостью.
                |Веди диалог в дружественном и профессиональном тоне.""".trimMargin()
        )

        /**
         * Агент шеф-повара.
         *
         * Помогает в приготовлении блюд, предоставляя подробные рецепты с историей происхождения,
         * списком ингредиентов и пошаговыми инструкциями. Дает профессиональные советы
         * по кулинарии и рекомендации по приготовлению.
         */
        val CHEF = Agent(
            id = "chef",
            name = "Шеф-повар",
            description = "Помощь в приготовлении блюд и рецептов",
            icon = "👨‍🍳",
            systemPrompt = """Ты - профессиональный шеф-повар с многолетним опытом работы.
                |Твоя задача - помогать людям в приготовлении различных блюд.
                |
                |Когда пользователь называет блюдо:
                |1. Расскажи краткую историю этого блюда и его происхождение
                |2. Предоставь подробный список ингредиентов с количеством
                |3. Дай пошаговые инструкции по приготовлению
                |4. Добавь полезные советы по приготовлению
                |
                |Будь дружелюбным и понятным в объяснениях. Если блюдо неизвестно или название неточное,
                |попроси уточнить или предложи похожие варианты.""".trimMargin()
        )

        /**
         * Универсальный агент-ассистент.
         *
         * Агент общего назначения для обычного диалога без специализированной роли.
         * Используется по умолчанию для свободного общения на любые темы.
         */
        val GENERAL_ASSISTANT = Agent(
            id = "general_assistant",
            name = "Универсальный ассистент",
            description = "Общение на любые темы",
            icon = "💬",
            systemPrompt = "Ты - полезный AI ассистент. Отвечай на вопросы пользователя в дружелюбном и профессиональном тоне."
        )

        /**
         * Возвращает список всех доступных предопределенных агентов.
         *
         * @return Список агентов в порядке приоритета отображения в UI
         */
        fun getAll(): List<Agent> = listOf(
            RESTAURANT_MANAGER,
            CHEF,
            GENERAL_ASSISTANT
        )

        /**
         * Находит агента по его уникальному идентификатору.
         *
         * @param id Уникальный идентификатор агента
         * @return Найденный агент или null, если агент с таким ID не существует
         */
        fun getById(id: String): Agent? = getAll().find { it.id == id }
    }
}